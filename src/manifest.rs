//! `aip.json` (what the user requires) and `aip.lock` (what was resolved), modelled on Composer.

use crate::registry::{self, RegistryConfig};
use crate::{Context, Error, Result};
use serde::ser::SerializeStruct;
use serde::{Deserialize, Deserializer, Serialize, Serializer, de};
use std::collections::BTreeMap;
use std::fmt;
use std::fs;
use std::io::ErrorKind;
use std::path::Path;

pub const MANIFEST_FILE: &str = "aip.json";
pub const LOCK_FILE: &str = "aip.lock";

#[derive(Debug, Default, Clone, PartialEq, Serialize, Deserialize)]
pub struct Manifest {
    /// Registries in priority order. Defaults to `$AIP_HOME/registry.json`.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub registries: Vec<RegistryConfig>,
    /// Provider ids (see `aip detect`) whose skill folders receive installed skills.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub providers: Vec<String>,
    /// Package name → version constraint, optionally with a folder name.
    #[serde(default)]
    pub require: BTreeMap<String, Requirement>,
    /// Unknown keys are kept as-is.
    #[serde(flatten)]
    pub extra: serde_json::Map<String, serde_json::Value>,
}

impl Manifest {
    /// `None` if the file does not exist.
    pub fn read(path: &Path) -> Result<Option<Self>> {
        read_json(path)
    }
}

/// A `require` entry: `"^1.0"`, or `{"version": "^1.0", "as": "other-name"}` to install the
/// skill under another folder name. Written back as a plain string when there is no alias.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Requirement {
    pub version: String,
    /// Folder name to install the skill as (`"as"`), instead of the skill's own name.
    pub alias: Option<String>,
}

impl From<&str> for Requirement {
    fn from(version: &str) -> Self {
        Self {
            version: version.to_string(),
            alias: None,
        }
    }
}

impl Serialize for Requirement {
    fn serialize<S: Serializer>(&self, serializer: S) -> std::result::Result<S::Ok, S::Error> {
        let Some(alias) = &self.alias else {
            return serializer.serialize_str(&self.version);
        };
        let mut object = serializer.serialize_struct("Requirement", 2)?;
        object.serialize_field("version", &self.version)?;
        object.serialize_field("as", alias)?;
        object.end()
    }
}

impl<'de> Deserialize<'de> for Requirement {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> std::result::Result<Self, D::Error> {
        #[derive(Deserialize)]
        #[serde(deny_unknown_fields)]
        struct Object {
            version: String,
            #[serde(rename = "as", default)]
            alias: Option<String>,
        }
        struct Visitor;
        impl<'de> de::Visitor<'de> for Visitor {
            type Value = Requirement;

            fn expecting(&self, f: &mut fmt::Formatter) -> fmt::Result {
                f.write_str(
                    r#"a version constraint or {"version": "<constraint>", "as": "<folder>"}"#,
                )
            }

            fn visit_str<E: de::Error>(self, version: &str) -> std::result::Result<Requirement, E> {
                Ok(version.into())
            }

            fn visit_map<A: de::MapAccess<'de>>(
                self,
                map: A,
            ) -> std::result::Result<Requirement, A::Error> {
                let object = Object::deserialize(de::value::MapAccessDeserializer::new(map))?;
                if let Some(alias) = object.alias.as_deref().filter(|a| !registry::valid_name(a)) {
                    return Err(de::Error::custom(format!(
                        "invalid \"as\" '{alias}' (use lowercase letters, digits, '.', '_', '-')"
                    )));
                }
                Ok(Requirement {
                    version: object.version,
                    alias: object.alias,
                })
            }
        }
        deserializer.deserialize_any(Visitor)
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Lock {
    #[serde(rename = "_readme", default)]
    pub readme: Vec<String>,
    #[serde(default)]
    pub packages: Vec<LockedPackage>,
}

impl Default for Lock {
    fn default() -> Self {
        Self {
            readme: vec![
                "This file locks the skills of your project to a known state".into(),
                "It is @generated by aip; do not edit it manually".into(),
            ],
            packages: Vec::new(),
        }
    }
}

impl Lock {
    /// An empty lock if the file does not exist.
    pub fn read(path: &Path) -> Result<Self> {
        Ok(read_json(path)?.unwrap_or_default())
    }

    pub fn get(&self, name: &str) -> Option<&LockedPackage> {
        self.packages.iter().find(|p| p.name == name)
    }

    /// Inserts or replaces a package, keeping packages sorted by name.
    pub fn upsert(&mut self, package: LockedPackage) {
        self.packages.retain(|p| p.name != package.name);
        self.packages.push(package);
        self.packages.sort_by(|a, b| a.name.cmp(&b.name));
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct LockedPackage {
    pub name: String,
    /// Tag version (`1.2.0`) or branch (`dev-main`).
    pub version: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
    pub source: Source,
    /// Skill folder inside the repository.
    pub path: String,
    /// Folder name the skill is installed as, from `"as"` in aip.json.
    #[serde(rename = "as", default, skip_serializing_if = "Option::is_none")]
    pub alias: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Source {
    #[serde(rename = "type")]
    pub kind: String,
    pub url: String,
    /// Commit SHA.
    pub reference: String,
}

impl Source {
    pub fn git(url: impl Into<String>, reference: impl Into<String>) -> Self {
        Self {
            kind: "git".into(),
            url: url.into(),
            reference: reference.into(),
        }
    }
}

fn read_json<T: for<'de> Deserialize<'de>>(path: &Path) -> Result<Option<T>> {
    let text = match fs::read_to_string(path) {
        Ok(text) => text,
        Err(e) if e.kind() == ErrorKind::NotFound => return Ok(None),
        Err(e) => return Err(Error::new(format!("cannot read {}: {e}", path.display()))),
    };
    serde_json::from_str(&text)
        .map(Some)
        .context(|| format!("invalid {}", path.display()))
}

/// Writes `value` as Composer-style JSON (4-space indent, trailing newline).
/// Returns `false` without touching the file when the content is unchanged.
pub fn write_json<T: Serialize>(path: &Path, value: &T) -> Result<bool> {
    let mut buf = Vec::new();
    let formatter = serde_json::ser::PrettyFormatter::with_indent(b"    ");
    let mut serializer = serde_json::Serializer::with_formatter(&mut buf, formatter);
    value
        .serialize(&mut serializer)
        .context(|| format!("cannot serialize {}", path.display()))?;
    buf.push(b'\n');
    if fs::read(path).is_ok_and(|current| current == buf) {
        return Ok(false);
    }
    if let Some(parent) = path.parent().filter(|p| !p.as_os_str().is_empty()) {
        fs::create_dir_all(parent).context(|| format!("cannot create {}", parent.display()))?;
    }
    fs::write(path, buf).context(|| format!("cannot write {}", path.display()))?;
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn manifest_keeps_unknown_keys_and_sorts_require() {
        let text = r#"{"name": "me/project", "require": {"b/x": "^1.0", "a/y": "dev-main"}}"#;
        let manifest: Manifest = serde_json::from_str(text).unwrap();
        let out = serde_json::to_string(&manifest).unwrap();
        assert_eq!(
            out,
            r#"{"require":{"a/y":"dev-main","b/x":"^1.0"},"name":"me/project"}"#
        );
    }

    #[test]
    fn require_takes_a_string_or_an_object_with_alias() {
        let text = r#"{"require": {"a/pdf": "^1.0", "b/pdf": {"version": "^2.0", "as": "b-pdf"}, "c/x": {"version": "*"}}}"#;
        let manifest: Manifest = serde_json::from_str(text).unwrap();
        assert_eq!(manifest.require["a/pdf"], "^1.0".into());
        assert_eq!(
            manifest.require["b/pdf"],
            Requirement {
                version: "^2.0".into(),
                alias: Some("b-pdf".into())
            }
        );
        assert_eq!(
            serde_json::to_string(&manifest).unwrap(),
            r#"{"require":{"a/pdf":"^1.0","b/pdf":{"version":"^2.0","as":"b-pdf"},"c/x":"*"}}"#
        );
        for (bad, why) in [
            (
                r#"{"version": "*", "as": "Bad/Name"}"#,
                "invalid \"as\" 'Bad/Name'",
            ),
            (r#"{"version": "*", "alias": "x"}"#, "unknown field `alias`"),
            (r#"{"as": "x"}"#, "missing field `version`"),
            ("1", "a version constraint or"),
        ] {
            let text = format!(r#"{{"require": {{"a/b": {bad}}}}}"#);
            let err = serde_json::from_str::<Manifest>(&text)
                .unwrap_err()
                .to_string();
            assert!(err.contains(why), "{bad}: {err}");
        }
    }

    #[test]
    fn readme_example_parses() {
        let text = r#"{"registries": [{"type": "json", "path": "registry.json"}], "providers": ["codex"], "require": {"a/b": "^1.0"}}"#;
        let manifest: Manifest = serde_json::from_str(text).unwrap();
        assert_eq!(manifest.registries.len(), 1);
        let bad = r#"{"registries": [{"type": "carrier-pigeon"}]}"#;
        let err = serde_json::from_str::<Manifest>(bad)
            .unwrap_err()
            .to_string();
        assert!(err.contains("unknown variant `carrier-pigeon`"), "{err}");
    }

    #[test]
    fn lock_upsert_replaces_and_sorts() {
        let pkg = |name: &str, version: &str| LockedPackage {
            name: name.into(),
            version: version.into(),
            description: None,
            source: Source::git("u", "sha"),
            path: "skills/x".into(),
            alias: None,
        };
        let mut lock = Lock::default();
        lock.upsert(pkg("b/x", "1.0.0"));
        lock.upsert(pkg("a/x", "1.0.0"));
        lock.upsert(pkg("b/x", "2.0.0"));
        let names: Vec<_> = lock
            .packages
            .iter()
            .map(|p| (&*p.name, &*p.version))
            .collect();
        assert_eq!(names, [("a/x", "1.0.0"), ("b/x", "2.0.0")]);
    }
}
